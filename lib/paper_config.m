function cfg=paper_config(root,runName)
% 设置求解参数和结果目录。
cfg=struct('execute',true, ...
 'solver','auto', ...
 'lpSeconds',60, ...
 'feasTol',3e-7, ...
 'lpGapTol',1e-6, ...
 'dwGapTol',1e-7, ...
 'priceTol',1e-10, ...
 'maxIterations',3000, ...
 'dwSeconds',7200, ...
 'writeLogs',false);
cfg.outDir=fullfile(root,'results',runName);
if ~exist(cfg.outDir,'dir'),mkdir(cfg.outDir);end
cfg.logDir=fullfile(cfg.outDir,'logs');cfg.caseDir=cfg.outDir;
end
